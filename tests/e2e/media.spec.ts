import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';

test('giảng viên upload thật, reload, phát video, xuất bản và học viên đăng ký xem', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email').fill('instructor@e2e.example');
  await page.getByLabel('Mật khẩu').fill('E2E-only-password-123');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await page.getByLabel('Tên khóa học mới').fill('Python: Từ nền tảng đến ứng dụng');
  await page.getByRole('button', { name: 'Tạo bản nháp' }).click();
  await page.screenshot({ path: 'test-results/studio-library.png', fullPage: true });
  await page.getByRole('button', { name: 'Quản lý bài giảng' }).click();
  await page.getByLabel('Tên chương mới').fill('Bắt đầu cùng Python');
  await page.getByRole('button', { name: 'Thêm chương', exact: true }).click();
  await page.getByLabel('Tên bài học', { exact: true }).fill('Bài giảng đầu tiên');
  await page.getByRole('button', { name: 'Thêm bài học', exact: true }).click();
  await page.getByLabel('Video cho Bài giảng đầu tiên').setInputFiles(resolve('.local/test-fixtures/browser.mp4'));
  await expect(page.getByRole('button', { name: 'Xem video', exact: true })).toBeVisible({ timeout: 30000 });
  await page.reload();
  await page.getByRole('button', { name: 'Quản lý bài giảng' }).click();
  await expect(page.getByText('Sẵn sàng', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Xem video', exact: true }).click();
  await expect.poll(() => page.locator('video').evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(1);
  await page.locator('video').evaluate((v: HTMLVideoElement) => { v.currentTime = 1; });
  await expect.poll(() => page.locator('video').evaluate((v: HTMLVideoElement) => v.currentTime)).toBeGreaterThanOrEqual(0.9);
  await page.screenshot({ path: 'test-results/studio-editor.png', fullPage: true });
  await page.getByRole('button',{name:'Thêm bài kiểm tra',exact:true}).click();
  await page.getByLabel('Tên bài kiểm tra',{exact:true}).fill('Ôn tập bài học đầu tiên');
  await page.getByLabel('Nội dung câu hỏi',{exact:true}).fill('Giá trị của 1 + 1 là bao nhiêu?');
  for(let i=1;i<=4;i++)await page.getByLabel(`Câu 1, lựa chọn ${i}`,{exact:true}).fill(String(i+1));
  await page.getByRole('button',{name:'Lưu bài kiểm tra',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Ôn tập bài học đầu tiên'})).toBeVisible();
  await page.evaluate(()=>document.fonts.ready);
  expect(await page.evaluate(()=>document.fonts.check('600 16px "Be Vietnam Pro"','Tiếng Việt: Ắ Ễ ự Đ đ'))).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/studio-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Xuất bản khóa học', exact: true }).click();
  await expect(page.getByLabel('Video cho Bài giảng đầu tiên')).toHaveCount(0);
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await expect(page.locator('video')).toHaveCount(0);
  await page.getByRole('button', { name: 'Chưa có tài khoản? Đăng ký' }).click();
  await page.getByLabel('Họ và tên').fill('Học viên video');
  await page.getByLabel('Email').fill(`media-${Date.now()}@e2e.example`);
  await page.getByLabel('Mật khẩu').fill('E2E-only-password-123');
  await page.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click();
  await page.getByRole('button', { name: 'Mở khóa học' }).click();
  await page.getByRole('button', { name: 'Đăng ký học', exact: true }).click();
  await page.getByRole('button', { name: 'Xem video', exact: true }).click();
  await expect.poll(() => page.locator('video').evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(1);
  await expect(page.getByLabel('Video cho Bài giảng đầu tiên')).toHaveCount(0);
  await page.getByRole('button',{name:'Làm bài',exact:true}).click();
  await page.getByLabel('2',{exact:true}).check();
  await page.getByRole('button',{name:'Nộp bài',exact:true}).click();
  await expect(page.getByText('Đạt · 1/1 câu đúng · 100.0 điểm',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/student-quiz-mobile.png',fullPage:true});
});

test('tệp hỏng hiển thị lỗi và cho phép thay bằng video hợp lệ', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email').fill('instructor@e2e.example');
  await page.getByLabel('Mật khẩu').fill('E2E-only-password-123');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await page.getByLabel('Tên khóa học mới').fill('Kiểm thử upload lỗi');
  await page.getByRole('button', { name: 'Tạo bản nháp' }).click();
  await page.locator('.courses li').filter({ hasText: 'Kiểm thử upload lỗi' }).getByRole('button', { name: 'Quản lý bài giảng' }).click();
  await page.getByLabel('Tên chương mới').fill('Chương thử');
  await page.getByRole('button', { name: 'Thêm chương', exact: true }).click();
  await page.getByLabel('Tên bài học', { exact: true }).fill('Video lỗi');
  await page.getByRole('button', { name: 'Thêm bài học', exact: true }).click();
  await page.getByLabel('Video cho Video lỗi').setInputFiles({ name: 'bad.mp4', mimeType: 'video/mp4', buffer: Buffer.from('not a video') });
  await expect(page.getByText('Xử lý thất bại', { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole('button', { name: 'Xuất bản khóa học' })).toBeDisabled();
  await page.getByLabel('Video cho Video lỗi').setInputFiles(resolve('.local/test-fixtures/browser.mp4'));
  await expect(page.getByRole('button', { name: 'Xem video', exact: true })).toBeVisible({ timeout: 30000 });
});
